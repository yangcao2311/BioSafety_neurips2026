#!/usr/bin/env python3
"""
T6.1 ADMET Adversarial Probe
Tests whether molecules generated by T4.1/T4.3 can fool ADMET-AI predictions.
Evaluates: (1) cross-predictor consistency, (2) adversarial shift from original toxicity.

Datasets:
  - ClinTox full: 112 CT_TOX=1 (FDA-failed clinical trials) + 100 FDA-approved negatives
  - T4.1 filled SMILES (ChemBERTa/MolFormer generated)
  - T4.3 GPT-4o optimized SMILES
"""
import json
import os
import gzip
import csv
import urllib.request
import warnings
warnings.filterwarnings("ignore")
import torch
torch.set_float32_matmul_precision('medium')
from datetime import datetime

BASE = "/home/ycao95/BioSafety/Task/SmallMolecule/T6.1 ADMET Adversarial Probe"
T41_CASCADE = "/home/ycao95/BioSafety/Task/SmallMolecule/T4.1 Small Molecule Mask & Fill/results/cascade/cascade_results_real.json"
T43_CASCADE = "/home/ycao95/BioSafety/Task/SmallMolecule/T4.3 NL-Guided Small Molecule Optimization/results/cascade/cascade_results_real.json"
RESULTS_DIR = os.path.join(BASE, "results/predictions")
os.makedirs(RESULTS_DIR, exist_ok=True)

CLINTOX_CACHE = os.path.join(RESULTS_DIR, "clintox_data.json")
CLINTOX_URL = "https://deepchemdata.s3-us-west-1.amazonaws.com/datasets/clintox.csv.gz"


def load_clintox_full():
    """Load full ClinTox dataset (1484 compounds, 112 CT_TOX=1)."""
    # Use cached version if available
    if os.path.exists(CLINTOX_CACHE):
        with open(CLINTOX_CACHE) as f:
            d = json.load(f)
        return d["toxic"], d["safe"]

    try:
        tmp = os.path.join(RESULTS_DIR, "clintox.csv.gz")
        print("  Downloading ClinTox dataset...")
        urllib.request.urlretrieve(CLINTOX_URL, tmp)
        with gzip.open(tmp, "rt") as f:
            reader = csv.DictReader(f)
            rows = list(reader)
        os.unlink(tmp)
        toxic = [{"smiles": r["smiles"], "source": "clintox_toxic",
                  "known_toxic": True, "label": "TOXIC"} for r in rows
                 if r.get("CT_TOX", "0") == "1" and r.get("smiles")]
        safe = [{"smiles": r["smiles"], "source": "clintox_safe",
                 "known_toxic": False, "label": "SAFE"} for r in rows
                if r.get("FDA_APPROVED", "0") == "1" and r.get("CT_TOX", "0") == "0"
                and r.get("smiles")]
        # Cache results
        with open(CLINTOX_CACHE, "w") as f:
            json.dump({"toxic": toxic, "safe": safe}, f)
        print(f"  ClinTox: {len(toxic)} toxic, {len(safe)} safe")
        return toxic, safe
    except Exception as e:
        print(f"  ClinTox download failed ({e}), using fallback set")
        return _fallback_clintox()


